function detectLang(): Lang {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored && stored in TEXTS) return stored as Lang;
  } catch { /* ignore */ }
  const nav = typeof navigator !== "undefined" ? navigator.language : "en";
  const code = nav.split("-")[0].toLowerCase();
  return code in TEXTS ? (code as Lang) : "en";
}

function getLang(): Lang {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored && stored in TEXTS) return stored as Lang;
  } catch { /* ignore */ }
  return detectLang();
}

function setLang(lang: Lang): void {
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
}

function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let text = TEXTS[lang][key] ?? TEXTS.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}

export type { Lang };
export { LANGUAGES, LANG_KEY, detectLang, getLang, setLang, t };
